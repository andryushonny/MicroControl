Z_STEP_MAX = 1000             # мкм: наибольший подъём за одну команду
Z_RANGE = 50000               # мкм: ход Z по умолчанию — от точки подключения ±50 мм (m.set_limits() — изменить)


def z_limits(wd):
    """Подъём за одну команду из рабочего расстояния WD (мкм): <= WD/3 (две ошибочные команды подряд ещё не касаются
    образца) и <= 1000 мкм; округление вниз до 50 мкм."""
    return max(min(Z_STEP_MAX, wd / 3) // 50 * 50, 50.0)
WINDOW_SIZE = (1280, 900)     # окно manual и view (одно на все режимы; последний размер помнится)
SCAN_OVERLAP = 0.30            # перекрытие соседних кадров скана (30 %; 50x, 100x — 35 %), сшивка по перекрытиям


def scan_overlap(objective):
    """Перекрытие кадров: 30 %, на 50x и 100x — 35 % (кадр мал, деталей в шве меньше). Больше перекрытие —
    надёжнее сшивка и края кадров (где оптика хуже) закрыты центрами соседних; кадров больше примерно в 1,3 раза."""
    return SCAN_OVERLAP + 0.05 if objective >= 50 else SCAN_OVERLAP


